CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
    unidad VARCHAR(30) NOT NULL CHECK (length(trim(unidad)) > 0),
    stock_minimo NUMERIC NOT NULL CHECK (stock_minimo >= 0),
    cantidad_objetivo NUMERIC NOT NULL CHECK (cantidad_objetivo > stock_minimo),
    stock NUMERIC NOT NULL DEFAULT 0 CHECK (stock >= 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
